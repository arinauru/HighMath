import numpy as np
from scipy.optimize import minimize

# Метод максимального правдоподобия:
# pdf — функция плотности, x — выборка, p0 — начальное приближение параметров
def MLE(pdf, x, p0):
    # Максимизация логарифма правдоподобия
    # эквивалентна минимизации его отрицательного значения
    return minimize(lambda p: -np.log(pdf(x, p)).sum(), p0).x

# Плотность нормального распределения N(mu, 1),
# где p[0] = mu — оцениваемое математическое ожидание
pdf = lambda x, p: np.exp(-(x - p[0])**2 / 2) / np.sqrt(2 * np.pi)

# Исходная выборка
x = np.array([1, 2, 3, 4, 5])

# Оценка параметра mu методом максимального правдоподобия
print(MLE(pdf, x, [0]))